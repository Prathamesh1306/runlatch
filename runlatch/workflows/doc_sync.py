def _local_doc_pr_tool() -> RegisteredTool:
    async def github_create_pr(
        title: str, body: str, head: str, base: str = "main"
    ) -> dict[str, object]:
        """Open a GitHub Pull Request for documentation updates (RiskTier.EXTERNAL)."""
        return {
            "title": title,
            "body": body,
            "head": head,
            "base": base,
            "html_url": "https://github.com/demo/repo/pull/110",
            "status": "created",
        }

    return FunctionTool(
        github_create_pr,
        name="github_create_pr",
        risk=RiskTier.EXTERNAL,
        requires_approval=True,
    )


def build_doc_sync_workflow(
    provider: LLMProvider,
    *,
    workspace_root: Path | str = ".",
    max_cost_usd: float = 0.20,
    store: CheckpointStore | None = None,
    policy: PolicyEvaluator | None = None,
    redactor: SecretRedactorProtocol | None = None,
    publish_tools: list[RegisteredTool] | None = None,
) -> Workflow:
    """Construct the multi-step `doc-sync` Workflow with HITL approval gate."""
    root = Path(workspace_root).resolve()
    active_policy = policy or PolicyEngine(auto_approve_max_tier=RiskTier.WRITE)
    active_redactor = redactor or SecretRedactor()

    file_tk = FileToolkit(root)
    git_tk = GitToolkit(root)
    patcher = git_tk.patcher if (root / ".git").exists() else None
    read_tools = [
        t
        for t in [*git_tk.tools(), *file_tk.tools()]
        if t.spec.risk_tier == RiskTier.READ
    ]

    inspector = Agent(
        name="doc-drift-inspector",
        provider=provider,
        tools=read_tools,
        system_prompt="You compare public Python/CLI changes against README.md for doc drift.",
        policy=active_policy,
        redactor=active_redactor,
        store=store,
    )

    pub_tool_list = publish_tools if publish_tools is not None else [_local_doc_pr_tool()]
    proposer = Agent(
        name="doc-pr-proposer",
        provider=provider,
        tools=pub_tool_list,
        system_prompt="You open a documentation sync Pull Request via github_create_pr.",
        policy=active_policy,
        redactor=active_redactor,
        patcher=patcher,
        store=store,
    )

    return (
        Workflow(name="doc-sync", max_cost_usd=max_cost_usd, store=store)
        .add_step(
            Step(
                name="inspect_api_diff",
                agent=inspector,
                prompt="Check git_diff and README.md for public API or CLI drift.",
                output_key="drift_analysis",
            )
        )
        .add_step(
            Step(
                name="propose_doc_patch",
                agent=proposer,
                prompt=(
                    "Propose a documentation cleanup PR based on:\n{drift_analysis}\n"
                    "Call github_create_pr."
                ),
                output_key="doc_pr_output",
            )
        )
    )
